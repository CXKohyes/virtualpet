package com.virtualpet.game;

/**
 * 玩家对宠物执行的操作（PRD 2.4）。
 *
 * <p>批次 1 只定义枚举。各项操作的效果、冷却、经验与幂等处理属于批次 2 的
 * {@code PetActionService}。</p>
 */
public enum PetAction {

    /** 喂食：饱食 +30、心情 +3、清洁 -2，经验 6。 */
    FEED,

    /** 玩耍：心情 +22、精力 -12、饱食 -5、清洁 -4，经验 8。 */
    PLAY,

    /** 清洁：清洁 +35、心情 +5，经验 6。 */
    CLEAN,

    /** 睡觉：精力 +10/小时，其余缓慢衰减。 */
    SLEEP,

    /** 唤醒：提前结束睡觉，按已睡整小时结算。 */
    WAKE
}
